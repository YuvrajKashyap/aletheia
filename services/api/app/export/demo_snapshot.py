TEXT_PREVIEW_CHARS = 500


@dataclass(frozen=True)
class SnapshotLimits:
    scenario_limit: int = 4
    trace_limit: int = 20
    evaluation_limit: int = 20
    document_limit: int = 20
    chunk_limit: int = 20
    query_limit: int = 20
    qrel_limit: int = 20
    replay_limit: int = 20
    include_large_text: bool = False


def json_safe(value: Any) -> Any:
    if isinstance(value, UUID):
        return str(value)
    if isinstance(value, datetime):
        return value.astimezone(timezone.utc).isoformat()
    if isinstance(value, date):
        return value.isoformat()
    if isinstance(value, Decimal):
        return float(value)
    if isinstance(value, Enum):
        return value.value
    if isinstance(value, dict):
        return {str(key): json_safe(nested) for key, nested in value.items()}
    if isinstance(value, (list, tuple, set)):
        return [json_safe(item) for item in value]
    return value


def truncate_text(value: str | None, include_large_text: bool, max_chars: int = TEXT_PREVIEW_CHARS) -> str | None:
    if value is None or include_large_text or len(value) <= max_chars:
        return value
    return f"{value[:max_chars]}..."


def row_to_dict(row: Any, fields: list[str], include_large_text: bool = False) -> dict[str, Any]:
    item: dict[str, Any] = {}
    for field in fields:
        value = getattr(row, field)
        if field == "text":
            value = truncate_text(value, include_large_text)
        item[field] = json_safe(value)
    return item


def write_json(output_dir: Path, file_name: str, payload: dict[str, Any] | list[Any]) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    target = output_dir / file_name
    temp = target.with_suffix(f"{target.suffix}.tmp")
    temp.write_text(
        json.dumps(json_safe(payload), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    temp.replace(target)


def build_manifest(
    *,
    counts: dict[str, int],
    warnings: list[str],
    generated_at: datetime | None = None,
    files: list[str] | None = None,
) -> dict[str, Any]:
    return {
        "generated": True,
        "generated_at": json_safe(generated_at or datetime.now(timezone.utc)),
        "source": "local_full_stack_export",
        "project": "Aletheia",
        "demo_mode": "snapshot",
        "explanation": (
            "Real precomputed outputs generated by the full local Aletheia pipeline. "
            "Live public retrieval and admin jobs are disabled to avoid always-on "
            "infrastructure costs."
        ),
        "counts": counts,
        "files": files or SNAPSHOT_FILES,
        "warnings": warnings,
    }


def limited(statement: Select[tuple[Any]], limit: int) -> Select[tuple[Any]]:
    return statement.limit(max(0, limit))


def count_rows(db: Session, model: Any) -> int:
    return int(db.scalar(select(func.count(model.id))) or 0)


def latest_rows(db: Session, model: Any, limit: int, order_field: str = "created_at") -> list[Any]:
    field = getattr(model, order_field)
    return list(db.scalars(select(model).order_by(field.desc()).limit(max(0, limit))).all())


