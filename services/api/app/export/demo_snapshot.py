def trace_detail(db: Session, trace: QueryTrace, query: Query | None = None) -> dict[str, Any]:
    query_row = query or db.get(Query, trace.query_id)
    candidates = list(
        db.scalars(
            select(RetrievalCandidate)
            .where(RetrievalCandidate.trace_id == trace.id)
            .order_by(RetrievalCandidate.source.asc(), RetrievalCandidate.final_rank.asc().nullslast())
        ).all()
    )
    candidate_items = [candidate_item(candidate) for candidate in candidates]
    candidates_by_source: dict[str, list[dict[str, Any]]] = {}
    for item in candidate_items:
        source = str(item.get("source") or "unknown")
        candidates_by_source.setdefault(source, []).append(item)

    return {
        "trace_id": json_safe(trace.id),
        "query_id": json_safe(trace.query_id),
        "created_at": json_safe(trace.created_at),
        "query": query_item(query_row) if query_row else None,
        "trace_json": json_safe(trace.trace_json),
        "candidates": candidate_items,
        "candidates_by_source": candidates_by_source,
    }


def scenario_from_trace(db: Session, trace: QueryTrace, query: Query) -> dict[str, Any]:
    final_candidates = list(
        db.scalars(
            select(RetrievalCandidate)
            .where(RetrievalCandidate.trace_id == trace.id)
            .order_by(RetrievalCandidate.final_rank.asc().nullslast())
            .limit(10)
        ).all()
    )
    results: list[dict[str, Any]] = []
    for candidate in final_candidates:
        chunk = db.get(Chunk, candidate.chunk_id) if candidate.chunk_id else None
        document = db.get(Document, candidate.document_id) if candidate.document_id else None
        results.append(
            {
                "rank": candidate.final_rank,
                "chunk_id": json_safe(candidate.chunk_id),
                "document_id": json_safe(candidate.document_id),
                "title": document.title if document else None,
                "document_external_id": document.external_id if document else None,
                "chunk_external_id": chunk.external_id if chunk else None,
                "text": truncate_text(chunk.text if chunk else None, include_large_text=False),
                "score": candidate.reranker_score
                if candidate.reranker_score is not None
                else candidate.fusion_score
                if candidate.fusion_score is not None
                else candidate.dense_score
                if candidate.dense_score is not None
                else candidate.bm25_score,
                "score_breakdown": {
                    "bm25_score": candidate.bm25_score,
                    "dense_score": candidate.dense_score,
                    "fusion_score": candidate.fusion_score,
                    "reranker_score": candidate.reranker_score,
                    "bm25_rank": candidate.bm25_rank,
                    "dense_rank": candidate.dense_rank,
                    "fusion_rank": candidate.fusion_rank,
                    "rerank_rank": candidate.rerank_rank,
                },
                "token_count": chunk.token_count if chunk else None,
                "chunking_strategy": chunk.chunking_strategy if chunk else None,
                "chunking_version": chunk.chunking_version if chunk else None,
                "metadata_json": candidate.metadata_json,
            }
        )

    return {
        "scenario_id": f"{query.retrieval_mode}_{trace.id}",
        "label": f"{query.retrieval_mode} trace",
        "query": query.text,
        "retrieval_mode": query.retrieval_mode,
        "trace_id": json_safe(trace.id),
        "query_id": json_safe(query.id),
        "result_count": len(results),
        "results": json_safe(results),
        "latency_ms": query.total_latency_ms,
        "search_response": {
            "query_id": json_safe(query.id),
            "trace_id": json_safe(trace.id),
            "query": query.text,
            "retrieval_mode": query.retrieval_mode,
            "result_count": len(results),
            "results": json_safe(results),
            "latency_ms": query.total_latency_ms,
        },
        "explanation": (
            "Real precomputed retrieval output exported from a stored query trace. "
            "No live hosted retrieval is run for this scenario."
        ),
    }


def export_demo_snapshot(db: Session, output_dir: Path, limits: SnapshotLimits) -> dict[str, Any]:
    warnings: list[str] = []
    output_dir.mkdir(parents=True, exist_ok=True)

    counts = {
        "datasets": count_rows(db, Dataset),
        "documents": count_rows(db, Document),
        "chunks": count_rows(db, Chunk),
        "benchmark_queries": count_rows(db, BenchmarkQuery),
        "relevance_judgments": count_rows(db, RelevanceJudgment),
        "index_versions": count_rows(db, IndexVersion),
        "evaluation_runs": count_rows(db, EvaluationRun),
        "traces": count_rows(db, QueryTrace),
        "saved_queries": count_rows(db, SavedQuery),
        "query_replays": count_rows(db, QueryReplay),
    }

    datasets = [dataset_summary(db, dataset) for dataset in latest_rows(db, Dataset, 50)]
    documents = [
        row_to_dict(
            row,
            [
                "id",
                "dataset_id",
                "external_id",
                "title",
                "text",
                "source_url",
                "metadata_json",
                "created_at",
                "updated_at",
            ],
            include_large_text=limits.include_large_text,
        )
        for row in latest_rows(db, Document, limits.document_limit)
    ]
    chunks = [
        row_to_dict(
            row,
            [
                "id",
                "dataset_id",
                "document_id",
                "external_id",
                "chunk_index",
                "text",
                "token_count",
                "char_start",
                "char_end",
                "content_hash",
                "chunking_strategy",
                "chunking_version",
                "metadata_json",
                "created_at",
            ],
            include_large_text=limits.include_large_text,
        )
        for row in latest_rows(db, Chunk, limits.chunk_limit)
    ]
    benchmark_queries = [
        row_to_dict(row, ["id", "dataset_id", "external_id", "text", "split", "metadata_json", "created_at"])
        for row in latest_rows(db, BenchmarkQuery, limits.query_limit)
    ]
    qrels = [
        row_to_dict(
            row,
            [
                "id",
                "dataset_id",
                "query_id",
                "document_id",
                "query_external_id",
                "document_external_id",
                "relevance_score",
                "metadata_json",
                "created_at",
            ],
        )
        for row in latest_rows(db, RelevanceJudgment, limits.qrel_limit)
    ]

    active_index = db.scalar(select(IndexVersion).where(IndexVersion.is_active.is_(True)).limit(1))
    latest_index_versions = [index_version_item(row) for row in latest_rows(db, IndexVersion, 20)]
    latest_index_jobs = [index_job_item(row) for row in latest_rows(db, IndexJob, 20)]

    trace_pairs = list(
        db.execute(
            select(QueryTrace, Query)
            .join(Query, QueryTrace.query_id == Query.id)
            .order_by(QueryTrace.created_at.desc())
            .limit(max(limits.trace_limit, limits.scenario_limit * 4))
        ).all()
    )
    traces = [trace_detail(db, trace, query) for trace, query in trace_pairs[: limits.trace_limit]]

    scenarios: list[dict[str, Any]] = []
    seen_modes: set[str] = set()
    for trace, query in trace_pairs:
        if query.retrieval_mode in seen_modes:
            continue
        scenarios.append(scenario_from_trace(db, trace, query))
        seen_modes.add(query.retrieval_mode)
        if len(scenarios) >= limits.scenario_limit:
            break

    expected_modes = {"bm25", "dense", "hybrid", "hybrid_rerank"}
    missing_modes = sorted(expected_modes - seen_modes)
    if missing_modes:
        warnings.append(
            "No stored query traces were available for retrieval modes: " + ", ".join(missing_modes)
        )

    evaluation_runs = latest_rows(db, EvaluationRun, limits.evaluation_limit)
    evaluation_ids = [row.id for row in evaluation_runs]
    evaluation_results = []
    if evaluation_ids:
        evaluation_results = [
            evaluation_result_item(row)
            for row in db.scalars(
                select(EvaluationQueryResult)
                .where(EvaluationQueryResult.evaluation_run_id.in_(evaluation_ids))
                .order_by(EvaluationQueryResult.created_at.desc())
                .limit(limits.evaluation_limit * 5)
            ).all()
        ]
    evaluation_reports = [
        row_to_dict(row, ["id", "evaluation_run_id", "report_format", "report_path", "summary_json", "created_at"])
        for row in db.scalars(
            select(EvaluationReport).order_by(EvaluationReport.created_at.desc()).limit(limits.evaluation_limit)
        ).all()
    ]

    experiment_configs = [experiment_config_item(row) for row in latest_rows(db, ExperimentConfig, 100)]
    latest_evaluation_by_config: dict[str, dict[str, Any]] = {}
    for run in evaluation_runs:
        if run.experiment_config_id and str(run.experiment_config_id) not in latest_evaluation_by_config:
            latest_evaluation_by_config[str(run.experiment_config_id)] = evaluation_run_item(run)

    saved_queries = [
        row_to_dict(row, ["id", "dataset_id", "name", "text", "source", "metadata_json", "created_at", "updated_at"])
        for row in latest_rows(db, SavedQuery, limits.query_limit)
    ]
    query_replays = [
        row_to_dict(
            row,
            [
                "id",
                "saved_query_id",
                "original_query_id",
                "source_trace_id",
                "target_trace_id",
                "experiment_config_id",
                "index_version_id",
                "status",
                "comparison_json",
                "error_message",
                "started_at",
                "completed_at",
                "created_at",
                "updated_at",
            ],
        )
        for row in latest_rows(db, QueryReplay, limits.replay_limit)
    ]
    system_events = [
        row_to_dict(
            row,
            [
                "id",
                "event_type",
                "severity",
                "message",
                "request_id",
                "job_id",
                "trace_id",
                "metadata_json",
                "created_at",
            ],
        )
        for row in latest_rows(db, SystemEvent, 50)
    ]

    index_status = {
        "active_index_version": index_version_item(active_index) if active_index else None,
        "latest_index_versions": latest_index_versions,
        "latest_index_jobs": latest_index_jobs,
        "dataset_count": counts["datasets"],
        "index_version_count": counts["index_versions"],
        "ready_index_version_count": int(
            db.scalar(select(func.count(IndexVersion.id)).where(IndexVersion.status == "ready")) or 0
        ),
        "active_index_version_count": int(
            db.scalar(select(func.count(IndexVersion.id)).where(IndexVersion.is_active.is_(True))) or 0
        ),
    }

    overview = {
        "mode": "snapshot",
        "explanation": (
            "This hosted demo uses real precomputed outputs generated by the full local Aletheia pipeline. "
            "Live retrieval, index rebuilds, and admin jobs are disabled publicly to avoid always-on search "
            "and ML infrastructure costs."
        ),
        "active_index": index_status["active_index_version"],
        "datasets": datasets,
        "latest_evaluations": [evaluation_run_item(row) for row in evaluation_runs[:5]],
        "experiment_configs": experiment_configs[:8],
        "recent_traces": [
            {
                "trace_id": item["trace_id"],
                "query_id": item["query_id"],
                "query_text": item["query"]["text"] if item.get("query") else None,
                "retrieval_mode": item["query"]["retrieval_mode"] if item.get("query") else None,
                "status": item["query"]["status"] if item.get("query") else None,
                "total_latency_ms": item["query"]["total_latency_ms"] if item.get("query") else None,
                "created_at": item["created_at"],
            }
            for item in traces[:5]
        ],
        "saved_query_count": counts["saved_queries"],
        "query_replay_count": counts["query_replays"],
        "system_events": system_events[:5],
        "counts": counts,
    }

    system = {
        "mode": "snapshot",
        "backend_live": False,
        "live_admin_actions_enabled": False,
        "explanation": (
            "Public snapshot mode serves real exported outputs from the local full stack. "
            "It does not claim live hosted infrastructure health."
        ),
        "local_full_stack_components": [
            "FastAPI",
            "Postgres",
            "Redis/RQ",
            "OpenSearch",
            "Qdrant",
            "embedding model",
            "reranker",
        ],
        "public_hosted_components": ["Vercel frontend", "Neon schema", "static snapshot data"],
        "system_events": system_events,
    }

    payloads: dict[str, dict[str, Any]] = {
        "overview.json": overview,
        "index-status.json": index_status,
        "datasets.json": {
            "datasets": datasets,
            "document_samples": documents,
            "chunk_samples": chunks,
            "benchmark_query_samples": benchmark_queries,
            "relevance_judgment_samples": qrels,
        },
        "documents-sample.json": {"total": counts["documents"], "items": documents},
        "chunks-sample.json": {"total": counts["chunks"], "items": chunks},
        "benchmark-queries-sample.json": {"total": counts["benchmark_queries"], "items": benchmark_queries},
        "relevance-judgments-sample.json": {"total": counts["relevance_judgments"], "items": qrels},
        "search-scenarios.json": {"items": scenarios, "warnings": warnings},
        "traces.json": {"total": counts["traces"], "items": traces},
        "evaluations.json": {
            "runs": [evaluation_run_item(row) for row in evaluation_runs],
            "query_results": evaluation_results,
            "reports": evaluation_reports,
        },
        "experiments.json": {
            "configs": experiment_configs,
            "latest_evaluation_by_config": latest_evaluation_by_config,
        },
        "replay.json": {
            "saved_queries": saved_queries,
            "query_replays": query_replays,
        },
        "system.json": system,
    }

    for file_name, payload in payloads.items():
        write_json(output_dir, file_name, payload)

    manifest = build_manifest(counts=counts, warnings=warnings, files=SNAPSHOT_FILES)
    write_json(output_dir, "manifest.json", manifest)
    return manifest
