    dataset_id = dataset.id
    return {
        **row_to_dict(
            dataset,
            [
                "id",
                "name",
                "source",
                "version",
                "description",
                "license_name",
                "license_url",
                "source_url",
                "metadata_json",
                "created_at",
                "updated_at",
            ],
        ),
        "document_count": int(
            db.scalar(select(func.count(Document.id)).where(Document.dataset_id == dataset_id)) or 0
        ),
        "chunk_count": int(db.scalar(select(func.count(Chunk.id)).where(Chunk.dataset_id == dataset_id)) or 0),
        "benchmark_query_count": int(
            db.scalar(select(func.count(BenchmarkQuery.id)).where(BenchmarkQuery.dataset_id == dataset_id)) or 0
        ),
        "relevance_judgment_count": int(
            db.scalar(select(func.count(RelevanceJudgment.id)).where(RelevanceJudgment.dataset_id == dataset_id)) or 0
        ),
    }


